export function getTeam(slug: string): Team | undefined {
  return teams.find((t) => t.slug === slug);
}

export function teamsBySection(): { section: (typeof sections)[number]; teams: Team[] }[] {
  return sections.map((section) => ({
    section,
    teams: teams.filter((t) => t.section === section.id).sort((a, b) => a.order - b.order),
  }));
}
